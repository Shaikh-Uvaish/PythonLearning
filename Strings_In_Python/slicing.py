name = "Am gonna be king of the pirates"
print(name[0:10]) #prints characters from index 0 to 9
#slicing means extracting a part of string out of main string
#in box braces [a:z] we give starting index as well as ending index separated by colon(:).
print(name[:6]) #replace the first empty number with 0 and it will print characters from index 0 to 5
print(name[7:]) #replace the second empty number with length-1 
